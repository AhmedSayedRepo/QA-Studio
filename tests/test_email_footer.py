"""Every QA Studio email ends with the same footer naming the app version and
the ACTIVE backend — never a hard-coded 'Azure DevOps'."""
import pathlib
import unittest
from unittest.mock import patch

import engine as E

ROOT = pathlib.Path(__file__).resolve().parents[1]


class FooterTests(unittest.TestCase):
    def tearDown(self):
        E.set_email_source("")

    def test_names_live_backend_and_version(self):
        current = {"name": "Jira + Zephyr Scale"}
        E.set_email_source(lambda: current["name"])
        with patch.object(E, "local_version", return_value="3.9.6"):
            self.assertEqual(E.email_footer_text(),
                             "Generated by QA Studio v3.9.6 · Jira + Zephyr Scale + AI")
            current["name"] = "TestRail"
            self.assertIn("TestRail + AI", E.email_footer_text())

    def test_explicit_source_note_and_fallback(self):
        with patch.object(E, "local_version", return_value="0.0.0"):
            self.assertEqual(E.email_footer_text(), "Generated by QA Studio · AI-assisted QA")
            self.assertIn("Test-case file + AI · note",
                          E.email_footer_text(source="Test-case file", note="note"))

    def test_html_is_escaped_and_has_logo_row(self):
        E.set_email_source("A & B")
        h = E.email_footer_html(meta_html="<div>m</div>")
        self.assertIn("A &amp; B + AI", h)
        self.assertIn("&middot;", h)
        self.assertTrue(h.endswith("<div>m</div>"))

    def test_broken_source_callable_is_ignored(self):
        E.set_email_source(lambda: 1 / 0)
        self.assertIn("AI-assisted QA", E.email_footer_text())

    def test_no_hard_coded_azure_footer_left(self):
        for name in ("engine.py", "task_manager.py", "regression.py", "performance.py",
                     "perf/report.py"):
            self.assertNotIn("Azure DevOps + AI", (ROOT / name).read_text(encoding="utf-8"), name)
        main = (ROOT / "main.py").read_text(encoding="utf-8")
        self.assertIn("E.set_email_source(lambda: backend_setup.label_for(", main)

    def test_every_builder_uses_the_shared_footer(self):
        eng = (ROOT / "engine.py").read_text(encoding="utf-8")
        self.assertGreaterEqual(eng.count("footer = email_footer_html("), 4)
        for name in ("task_manager.py", "regression.py"):
            self.assertIn("E.email_footer_html(", (ROOT / name).read_text(encoding="utf-8"))
        self.assertIn('meta.get("footer_label")',
                      (ROOT / "perf" / "report.py").read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()
